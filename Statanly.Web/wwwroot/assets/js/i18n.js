function applyLanguage(lang) {
  const pack = I18N[lang] || I18N.en;
  const meta = LANG_META[lang] || LANG_META.en;

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (pack[key]) {
      el.textContent = pack[key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (pack[key]) {
      el.innerHTML = pack[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (pack[key]) {
      el.setAttribute("placeholder", pack[key]);
    }
  });

  document.querySelectorAll("[data-i18n-value]").forEach((el) => {
    const key = el.getAttribute("data-i18n-value");
    if (pack[key]) {
      el.setAttribute("value", pack[key]);
    }
  });

  const current = document.querySelector(".lang-current");
  if (current) {
    const flag = current.querySelector(".lang-flag") || current.querySelector(".flag-icon");
    const code = current.querySelector(".lang-code");

    if (flag) flag.className = `${meta.flagClass} lang-flag`;
    if (code) code.textContent = meta.code;
  }

  document.querySelectorAll(".lang-option").forEach((item) => {
    item.classList.toggle("active", item.getAttribute("data-lang") === lang);
  });

  localStorage.setItem("statanly_lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const saved = localStorage.getItem("statanly_lang") || "en";
  applyLanguage(saved);

  document.querySelectorAll(".lang-option").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.getAttribute("data-lang"));
    });
  });
});
